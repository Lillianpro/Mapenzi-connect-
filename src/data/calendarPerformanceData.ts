// Helper to get all performances for a month (format 'YYYY-MM')
export function getMonthPerformanceStats(year: number, month: number) {
  const monthStr = `${year}-${String(month).padStart(2, '0')}`;
  const daysInMonth = new Date(year, month, 0).getDate();
  
  let totalWins = 0;
  let totalLosses = 0;
  let totalPicks = 0;
  let winningDays = 0;
  let mixedDays = 0;
  let losingDays = 0;
  let activeDays = 0;

  for (let d = 1; d <= daysInMonth; d++) {
    const dayKey = `${monthStr}-${String(d).padStart(2, '0')}`;
    const rec = MONTHLY_PERFORMANCE_RECORDS[dayKey];
    if (rec && (rec.status === 'win' || rec.status === 'mixed' || rec.status === 'loss' || rec.status === 'today')) {
      activeDays++;
      totalWins += rec.wins;
      totalLosses += rec.losses;
      totalPicks += rec.totalPicks;
      if (rec.status === 'win') winningDays++;
      else if (rec.status === 'mixed') mixedDays++;
      else if (rec.status === 'loss') losingDays++;
      else if (rec.status === 'today' && rec.wins > rec.losses) winningDays++;
    }
  }

  const overallWinRate = totalPicks > 0 ? ((totalWins / (totalWins + totalLosses || 1)) * 100).toFixed(1) : '0.0';

  return {
    totalWins,
    totalLosses,
    totalPicks,
    winningDays,
    mixedDays,
    losingDays,
    activeDays,
    overallWinRate: parseFloat(overallWinRate),
  };
}
